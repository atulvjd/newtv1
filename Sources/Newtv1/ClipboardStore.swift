import AppKit
import SwiftUI

@MainActor
final class ClipboardStore: ObservableObject {
    struct Entry: Identifiable {
        let id = UUID()
        let text: String?
        let image: Data?
        let files: [URL]
        let date = Date()
        var label: String { text.map { String($0.prefix(100)) } ?? (files.isEmpty ? "Copied image" : files.map(\.lastPathComponent).joined(separator: ", ")) }
    }
    struct Snippet: Codable, Identifiable { var id = UUID(); var name: String; var text: String }
    @Published var enabled = false { didSet { lastChange = NSPasteboard.general.changeCount } }
    @Published private(set) var entries: [Entry] = []
    @Published var snippets: [Snippet] { didSet { if let data = try? JSONEncoder().encode(snippets) { UserDefaults.standard.set(data, forKey: "textSnippets") } } }
    private var lastChange = NSPasteboard.general.changeCount
    init() { snippets = UserDefaults.standard.data(forKey: "textSnippets").flatMap { try? JSONDecoder().decode([Snippet].self, from: $0) } ?? [] }
    func poll() {
        let board = NSPasteboard.general
        guard enabled, board.changeCount != lastChange else { return }
        lastChange = board.changeCount
        let excluded = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        guard !(board.types ?? []).contains(where: { excluded.contains($0.rawValue) }) else { return }
        let text = board.string(forType: .string).map { String($0.prefix(16000)) }
        let files = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
        var image = board.data(forType: .png) ?? board.data(forType: .tiff)
        if let data = image, data.count > 2_000_000 { image = nil }
        guard text?.isEmpty == false || image != nil || !files.isEmpty else { return }
        if let first = entries.first, first.text == text, first.image == image, first.files == files { return }
        entries.insert(Entry(text: text, image: image, files: files), at: 0)
        entries = Array(entries.prefix(20))
    }
    func copy(_ entry: Entry) {
        let board = NSPasteboard.general; board.clearContents()
        if !entry.files.isEmpty { board.writeObjects(entry.files as [NSURL]) }
        else if let text = entry.text { board.setString(text, forType: .string) }
        else if let data = entry.image, let image = NSImage(data: data) { board.writeObjects([image]) }
        lastChange = board.changeCount
    }
    func copyText(_ text: String) { let board = NSPasteboard.general; board.clearContents(); board.setString(text, forType: .string); lastChange = board.changeCount }
    func clear() { entries = [] }
    func remove(_ id: UUID) { entries.removeAll { $0.id == id } }
}
